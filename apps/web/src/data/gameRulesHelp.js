/**
 * Статические подсказки «как играть» и легенды таблицы очков для мини-игр (не Мафия).
 * Динамические числа (бонусы из настроек) подставляются в RoomPage там, где нужно.
 */

/** @param {{ id: string, name: string, score?: number }[]} players @param {string} selfId */
export function buildRankedScoreRows(players, selfId) {
  if (!Array.isArray(players) || players.length === 0) return [];
  const sorted = [...players].sort((a, b) => {
    if ((b.score ?? 0) !== (a.score ?? 0)) return (b.score ?? 0) - (a.score ?? 0);
    return String(a.name || '').localeCompare(String(b.name || ''), 'ru');
  });
  let prevRank = 0;
  return sorted.map((p, i) => {
    const rank = i === 0 || (p.score ?? 0) < (sorted[i - 1].score ?? 0) ? i + 1 : prevRank;
    prevRank = rank;
    return {
      id: p.id,
      name: p.name,
      score: typeof p.score === 'number' && !Number.isNaN(p.score) ? p.score : Number(p.score) || 0,
      rank,
      isSelf: p.id === selfId,
      medal: rank === 1 ? '🥇' : rank === 2 ? '🥈' : rank === 3 ? '🥉' : null,
    };
  });
}

